import {
  callerPositions,
  PUSH_FOLD_DEPTHS,
  PUSH_POSITIONS,
  PUSHER_GROUPS,
  type PushChartFile,
  type PushFoldDepth,
  type PushFoldFiles,
  type PushPosition,
  pushersFacing,
  type VsPushChartFile,
} from "@/lib/charts/push-fold";
import { HAND_CLASS_COUNT } from "@/lib/poker/combo";
import { createRange, formatRange, setHandClassWeight } from "@/lib/poker/range";
import type { Position } from "@/lib/poker/table";
import { foldedTo, type PushFoldSolution } from "./nash";

/** Frequency as written in a Chart: mixes under 10% are dropped, above 90% become pure, the rest round to 5%. */
export function chartFrequency(frequency: number): number {
  if (frequency < 0.1) return 0;
  if (frequency > 0.9) return 1;
  return Math.round(frequency * 20) / 20;
}

/** Range string of per-Hand-class frequencies, rounded with `chartFrequency`. */
export function frequencyString(frequencies: Float64Array): string {
  const range = createRange();
  for (let cls = 0; cls < HAND_CLASS_COUNT; cls++) setHandClassWeight(range, cls, chartFrequency(frequencies[cls]));
  return formatRange(range);
}

/** Solution of the game folded to `pusher` at `depth`; its calls follow `foldedTo(pusher, depth).callers`. */
export type SolveFoldedTo = (depth: PushFoldDepth, pusher: PushPosition) => PushFoldSolution;

/**
 * Push and Vs push chart files from solved games. A Vs push chart averages the caller's frequencies
 * solved against each pusher of the group that acts before it.
 */
export function pushFoldFilesFrom(solve: SolveFoldedTo): PushFoldFiles {
  const push: Record<number, Record<string, { push: string }>> = {};
  const vsPush: Record<number, Record<string, Record<string, { call: string }>>> = {};
  for (const depth of PUSH_FOLD_DEPTHS) {
    const solutions = new Map(PUSH_POSITIONS.map((pusher) => [pusher, solve(depth, pusher)]));
    const callFrequencies = (pusher: Position, caller: Position) => {
      const solution = solutions.get(pusher as PushPosition);
      const index = foldedTo(pusher, depth).callers.indexOf(caller);
      if (!solution || index < 0) throw new Error(`No solution for ${caller} facing ${pusher} at ${depth}bb`);
      return solution.calls[index];
    };

    push[depth] = Object.fromEntries(PUSH_POSITIONS.map((pusher) => [pusher, { push: frequencyString(solutions.get(pusher)?.push ?? new Float64Array(HAND_CLASS_COUNT)) }]));
    vsPush[depth] = Object.fromEntries(
      PUSHER_GROUPS.map((group) => [
        group,
        Object.fromEntries(
          callerPositions(group).map((caller) => {
            const pushers = pushersFacing(caller, group);
            const average = new Float64Array(HAND_CLASS_COUNT);
            for (const pusher of pushers) {
              const calls = callFrequencies(pusher, caller);
              for (let cls = 0; cls < HAND_CLASS_COUNT; cls++) average[cls] += calls[cls] / pushers.length;
            }
            return [caller, { call: frequencyString(average) }];
          }),
        ),
      ]),
    );
  }
  return { push: { depths: push } as PushChartFile, "vs-push": { depths: vsPush } as VsPushChartFile };
}

const key = (name: string | number) => (typeof name === "number" || /^[A-Za-z_]\w*$/.test(name) ? String(name) : JSON.stringify(name));

function literal(value: unknown, indent: string): string {
  if (typeof value === "string") return JSON.stringify(value);
  const entries = Object.entries(value as Record<string, unknown>);
  const inner = `${indent}  `;
  const leaf = entries.every(([, child]) => typeof child === "string");
  if (leaf) return `{ ${entries.map(([name, child]) => `${key(name)}: ${literal(child, inner)}`).join(", ")} }`;
  const keyOf = (name: string) => (/^\d+$/.test(name) ? Number(name) : name);
  return `{\n${entries.map(([name, child]) => `${inner}${key(keyOf(name))}: ${literal(child, inner)},`).join("\n")}\n${indent}}`;
}

function header(situation: string, iterations: number): string {
  return `/**
 * ${situation}
 *
 * Generated by \`pnpm generate:push-fold\` (scripts/generate-push-fold.ts): a chip-EV Nash equilibrium for 8-max
 * with no antes and equal stacks (blinds 0.5 / 1bb), single-caller model (after the first call everyone behind
 * folds), ${iterations} iterations of fictitious play on exact all-in equities. Do not edit by hand; re-run the script.
 */`;
}

/** TypeScript source of the two Chart files (format with Biome after writing). */
export function pushFoldSources(files: PushFoldFiles, iterations: number): Record<keyof PushFoldFiles, string> {
  return {
    push: `${header("Push: folded to you, all-in or fold; fold is the remainder.", iterations)}
import type { PushChartFile } from "@/lib/charts/push-fold";

export const PUSH_CHARTS: PushChartFile = ${literal(files.push, "")};
`,
    "vs-push": `${header("Vs push: facing an all-in with everyone between folded, call or fold; fold is the remainder. Pushers are grouped\n * early (UTG, UTG+1), middle (LJ, HJ) and late (CO, BTN, SB); each Chart averages the call frequencies solved\n * against every pusher of the group that acts before you.", iterations)}
import type { VsPushChartFile } from "@/lib/charts/push-fold";

export const VS_PUSH_CHARTS: VsPushChartFile = ${literal(files["vs-push"], "")};
`,
  };
}
